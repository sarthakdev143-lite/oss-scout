const flagsOf = (docs: PolicyDoc[]) => aiPolicyFlags(classifyAiPolicy(docs))

describe("classifyAiPolicy", () => {
  for (const c of CASES) {
    test(c.name, () => {
      const r = classifyAiPolicy([{ path: c.path ?? "CONTRIBUTING.md", text: c.text }])
      expect(r.classification).toBe(c.cls)
      const flags = aiPolicyFlags(r)
      for (const f of c.flags ?? []) expect(flags).toContain(f)
      for (const f of c.notFlags ?? []) expect(flags).not.toContain(f)
      if (c.cls === "none_found") expect(r.evidence).toEqual([])
      if (c.cls !== "none_found" && c.cls !== "allowed") expect(r.evidence.length).toBeGreaterThan(0)
    })
  }

  test("no documents => none_found", () => {
    const r = classifyAiPolicy([])
    expect(r).toEqual({ classification: "none_found", evidence: [], requiresDisclosure: false, notes: [] })
  })

  test("most restrictive verdict wins across documents (permissive AGENTS.md vs prohibiting CONTRIBUTING)", () => {
    const r = classifyAiPolicy([
      { path: "AGENTS.md", text: "You may use AI tools to explore the codebase. AI-assisted contributions are welcome." },
      { path: "CONTRIBUTING.md", text: "## AI policy\n\nWe do not accept contributions generated by LLMs." },
    ])
    expect(r.classification).toBe("prohibited")
    expect(r.evidence[0]!.file).toBe("CONTRIBUTING.md")
    expect(r.evidence[0]!.rule).toBe("prohibit")
  })

  test("restricted beats disclosure-required across documents", () => {
    const r = classifyAiPolicy([
      { path: "CONTRIBUTING.md", text: "## AI policy\n\nYou must disclose AI usage in the PR description." },
      { path: ".github/AI_POLICY.md", text: "Absolutely no unsupervised agentic tools." },
    ])
    expect(r.classification).toBe("restricted")
  })

  test("PR template checkbox evidence carries the template path and rule", () => {
    const r = classifyAiPolicy([
      { path: "CONTRIBUTING.md", text: "## Contributing\n\nRun the tests." },
      { path: ".github/pull_request_template.md", text: "- [ ] I confirm I did not use AI tools for this change" },
    ])
    expect(r.classification).toBe("prohibited")
    expect(r.evidence[0]).toEqual({
      file: ".github/pull_request_template.md",
      excerpt: "I confirm I did not use AI tools for this change",
      rule: "no_ai_certification",
    })
  })

  test("HTML comments in templates are kept as text", () => {
    const r = classifyAiPolicy([
      { path: ".github/pull_request_template.md", text: "## Summary\n<!-- AI-generated pull requests are not accepted. -->\n" },
    ])
    expect(r.classification).toBe("prohibited")
  })

  test("evidence excerpts are capped at 300 chars", () => {
    const long = `## AI policy\n\nWe do not accept contributions generated by LLMs ${"because of licensing and provenance concerns ".repeat(20)}.`
    const r = classifyAiPolicy([{ path: "CONTRIBUTING.md", text: long }])
    expect(r.classification).toBe("prohibited")
    for (const e of r.evidence) expect(e.excerpt.length).toBeLessThanOrEqual(EVIDENCE_EXCERPT_CHARS)
  })

  test("requiresDisclosure follows the disclosure_required flag", () => {
    expect(classifyAiPolicy([{ path: "CONTRIBUTING.md", text: "## AI policy\n\nAI use must be disclosed." }]).requiresDisclosure).toBe(true)
    expect(
      classifyAiPolicy([{ path: "CONTRIBUTING.md", text: "## AI policy\n\nDisclosure is appreciated but not required. AI-assisted contributions are welcome." }])
        .requiresDisclosure,
    ).toBe(false)
  })

  test("unclear verdict explains itself in notes", () => {
    const r = classifyAiPolicy([{ path: "CONTRIBUTING.md", text: "## AI tools\n\nThis section will be expanded later." }])
    expect(r.notes.some((n) => /unclear/.test(n))).toBe(true)
    expect(r.evidence[0]!.rule).toBe("unclear")
  })

  test("org-level AI policy file path is treated as a whole-file policy", () => {
    const r = classifyAiPolicy([{ path: "acme/.github/AI_POLICY.md", text: "We do not allow autonomous agents to be used for contributing." }])
    expect(r.classification).toBe("restricted")
    expect(flagsOf([{ path: "acme/.github/AI_POLICY.md", text: "We do not allow autonomous agents to be used for contributing." }])).toContain(
      "no_autonomous_agents",
    )
  })

  test("large pathological documents classify quickly (unmatched ** globs, one huge paragraph)", () => {
    const huge = "Use the glob **/*.js for sources and __pycache__ dirs. ".repeat(6000)
    const started = performance.now()
    const r = classifyAiPolicy([{ path: "README.md", text: huge }, { path: "CONTRIBUTING.md", text: huge }])
    expect(r.classification).toBe("none_found")
    expect(performance.now() - started).toBeLessThan(3000)
  })

  test("deterministic: same input, same output", () => {
    const docs = [{ path: "CONTRIBUTING.md", text: CASES[8]!.text }]
    expect(classifyAiPolicy(docs)).toEqual(classifyAiPolicy(docs))
  })

  test("flags are exposed through notes and hasAiPolicyFlag", () => {
    const r = classifyAiPolicy([{ path: "CONTRIBUTING.md", text: CASES[9]!.text }])
    expect(hasAiPolicyFlag(r, "assisted_by_trailer")).toBe(true)
    expect(hasAiPolicyFlag(r, "agent_directive")).toBe(false)
    expect(r.notes.some((n) => n.startsWith("ai:assisted_by_trailer:"))).toBe(true)
  })
})

describe("policyBlocks", () => {
  const cls = (text: string, path = "CONTRIBUTING.md") => classifyAiPolicy([{ path, text }])

  test("prohibited => reason citing the evidence and file", () => {
    const reason = policyBlocks(cls("## AI policy\n\nWe do not accept AI-generated contributions."), false)
    expect(reason).toContain("prohibits")
    expect(reason).toContain("CONTRIBUTING.md")
    expect(reason).toContain("We do not accept AI-generated contributions.")
  })

  test("restricted => reason naming the restrictions", () => {
    const reason = policyBlocks(cls("## AI policy\n\nAbsolutely no unsupervised agentic tools."), false)
    expect(reason).toContain("restricts")
    expect(reason).toContain("no_autonomous_agents")
  })

  test("unclear_restrictive blocks only when skipUnclear is set", () => {
    const ai = cls("## Use of AI tools\n\nWe have concerns and decide case by case.")
    expect(ai.classification).toBe("unclear_restrictive")
    expect(policyBlocks(ai, true)).toContain("unclear")
    expect(policyBlocks(ai, false)).toBeNull()
  })

  test("allowed, disclosure_required and none_found never block", () => {
    expect(policyBlocks(cls("## AI policy\n\nAI-assisted contributions are welcome."), true)).toBeNull()
    expect(policyBlocks(cls("## AI policy\n\nYou must disclose AI usage."), true)).toBeNull()
    expect(policyBlocks(cls("## Contributing\n\nRun the tests."), true)).toBeNull()
  })
})

